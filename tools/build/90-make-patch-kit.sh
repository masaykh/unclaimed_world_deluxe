#!/bin/sh
# Builds kit/ - the build-from-source kit, which contains NO game code and NO game assets.
#
# WHY THIS EXISTS. The port is a derivative work of Unclaimed World: 1,496 of the 1,523 files in
# src/UnclaimedWorld are byte-identical to the decompiler's output, and the remaining 27 are the
# studio's files with our edits in them. None of that can be distributed. What CAN be
# distributed is the difference: a patch series, the files we wrote from scratch, the build
# system, and our own tools. The recipient supplies the game, decompiles their own copy, and
# applies this.
#
# So the rule this script enforces is simple: everything it emits is either
#   (a) ours outright - tools, build scripts, the new source files, the csproj files, or
#   (b) a DIFF, which describes a change without reproducing the thing changed.
#
# Deliberately NOT emitted:
#   decomp/, src/ wholesale       the studio's code
#   app.ico                       147 KB, extracted from their executable
#   Generated/XmlProxies/*.g.cs   generated from their types; the kit regenerates them locally
#   MainMenuIntro.uwanim          re-encode of their video; generated locally from the user's own
#   port-content/*.xnb            their shader bytecode; converted locally from the user's own
#
# Patch context is -U1 rather than the usual -U3: context lines ARE the original's text, so
# fewer of them means less of the studio's code in the diff. One line is enough for `patch` to
# locate a hunk reliably against a byte-identical decompile, which is what the recipient has.
set -e
. "$(dirname "$0")/env.sh"
cd "$UW_REPO"

KIT=${1:-kit}
PATCHES="$KIT/patches"
NEWFILES="$KIT/newfiles"

# decomp subtree -> src subtree. Matches build/11-rebaseline.sh: RoundLines and InputEventSystem
# are folded into the WindowSystem project, so all three decompiled assemblies map into it.
RULES="
UnclaimedWorld|src/UnclaimedWorld
WindowSystem|src/WindowSystem
RoundLines|src/WindowSystem
InputEventSystem|src/WindowSystem
SpriteSheetRuntime|src/SpriteSheetRuntime
Xclna.Xna.Animationx86|src/AnimationComponentRuntime
"

# Files that exist only in src/ but must NOT be shipped, because they are derived from the
# game rather than written by us.
is_excluded_newfile() {
  case "$1" in
    Generated/XmlProxies/*) return 0 ;;   # regenerated by tools/XmlProxyGen on the user's machine
    # LightSourceSpriteSheet is the STUDIO'S class, retained from game 1.0.3.5 so an older
    # LightSources.xnb can still resolve its reader. Game 1.0.4.8 deleted it, so it has no
    # counterpart in decomp/ and the automated "is this ours?" test cleared it - wrongly. The
    # kit targets 1.0.4.8, where nothing references it, so it is simply dropped.
    SpriteSheetRuntime/LightSourceSpriteSheet.cs) return 0 ;;
    *) return 1 ;;
  esac
}

# Studio-derived files that live outside src/ and so are not covered by the decomp comparison at
# all. Listed explicitly because the automated check cannot find them: it only knows about files
# with a counterpart in the CURRENT decompile.
#
# tools/XmlProxyGen/ProxyCodeGenerator.cs is the game's own CodeDom generator, moved out of
# CustomXmlSerializer by PORT DEVIATION 12 - its own header says "the game's original generator
# verbatim rather than a reworded copy". 14 KB of the studio's code, which was being shipped.
# It is emitted as a PATCH against the decompiled CustomXmlSerializer.cs instead: 32 added lines
# and 18 context lines, rather than 355 lines of theirs.
DERIVED_OUTSIDE_SRC="tools/XmlProxyGen/ProxyCodeGenerator.cs"

# Every generated directory is cleared, not just patches/ and newfiles/. Clearing only those two
# left a STALE tools/XmlProxyGen/ProxyCodeGenerator.cs behind from an earlier run - after the
# generator had been changed to stop shipping it - so the audit passed and the zip still carried
# 14 KB of the studio's code. Stale output is the failure mode a "no game code" check cannot see,
# because the check looks at what is there, not at why.
rm -rf "$PATCHES" "$NEWFILES" "$KIT/tools" "$KIT/projects" "$KIT/build"
mkdir -p "$PATCHES" "$NEWFILES"

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

total_same=0; total_mod=0; total_new=0; total_del=0; total_excluded=0

echo "==> generating patch series"
printf '%s\n' "$RULES" | while IFS='|' read -r asm dst; do
  [ -n "$asm" ] || continue
  [ -d "decomp/$asm" ] || { echo "    ! decomp/$asm missing - run build/10-decompile.sh"; continue; }

  same=0; mod=0; del=0
  patchfile="$PATCHES/$asm.patch"
  : > "$TMP/p"

  # WindowSystem, RoundLines and InputEventSystem all map into src/WindowSystem, and each has
  # its own Properties/AssemblyInfo.cs. Only the FIRST assembly mapped to a directory owns
  # Properties/: diffing RoundLines' AssemblyInfo against WindowSystem's produces a patch that
  # rewrites the merged project's identity, and applying two of them to one file is impossible
  # by construction. The merged assembly's identity is WindowSystem's, which is load-critical.
  primary=1
  case "$asm" in RoundLines|InputEventSystem) primary=0 ;; esac

  # Every decompiled file: identical, modified, or gone from src (deleted by the port).
  find "decomp/$asm" -name '*.cs' | sort | while IFS= read -r f; do
    rel=${f#decomp/$asm/}
    case "$rel" in Properties/*) [ "$primary" = 1 ] || continue ;; esac
    t="$dst/$rel"
    if [ ! -f "$t" ]; then
      printf '%s\n' "$rel" >> "$TMP/deleted.$asm"
      continue
    fi
    # Normalise line endings before comparing: .gitattributes checks out CRLF, and a diff of
    # nothing but line endings would put the entire file into the patch.
    tr -d '\r' < "$f" > "$TMP/a"; tr -d '\r' < "$t" > "$TMP/b"
    if cmp -s "$TMP/a" "$TMP/b"; then
      echo x >> "$TMP/same.$asm"
    else
      echo x >> "$TMP/mod.$asm"
      # Paths in the patch are relative to the project root so `patch -p1` works from there.
      diff -U1 --label "a/$rel" --label "b/$rel" "$TMP/a" "$TMP/b" >> "$TMP/p" || true
    fi
  done

  count() { [ -f "$1" ] && wc -l < "$1" | tr -d " " || echo 0; }
  same=$(count "$TMP/same.$asm")
  mod=$(count "$TMP/mod.$asm")
  del=$(count "$TMP/deleted.$asm")

  if [ -s "$TMP/p" ]; then mv "$TMP/p" "$patchfile"; fi
  if [ -f "$TMP/deleted.$asm" ]; then sort "$TMP/deleted.$asm" > "$PATCHES/$asm.deleted"; fi

  ctx=$(grep -c '^ ' "$patchfile" 2>/dev/null || echo 0)
  add=$(grep -c '^+[^+]' "$patchfile" 2>/dev/null || echo 0)
  printf '    %-24s %4s unchanged  %3s patched  %2s deleted   (+%s ours, %s context lines)\n' \
    "$asm" "$same" "$mod" "$del" "$add" "$ctx"
done

echo
echo "==> collecting the files we wrote"
printf '%s\n' "$RULES" | while IFS='|' read -r asm dst; do
  [ -n "$asm" ] || continue
  [ -d "$dst" ] || continue
  find "$dst" -name '*.cs' -not -path '*/obj/*' -not -path '*/bin/*' | sort | while IFS= read -r t; do
    rel=${t#$dst/}
    # Only files with no counterpart in ANY decompiled tree are ours.
    ours=1
    for a in UnclaimedWorld WindowSystem RoundLines InputEventSystem SpriteSheetRuntime Xclna.Xna.Animationx86; do
      [ -f "decomp/$a/$rel" ] && { ours=0; break; }
    done
    [ "$ours" = 1 ] || continue
    if is_excluded_newfile "$rel"; then echo x >> "$TMP/excl"; continue; fi
    mkdir -p "$NEWFILES/$(dirname "$dst/$rel")"
    cp -p "$t" "$NEWFILES/$dst/$rel"
    echo x >> "$TMP/new"
  done
done
# Sweep everything else under src/ as well. The loop above only visits the directories in
# RULES, which misses shared sources that belong to no single decompiled assembly - src/Shared/
# AssemblyPlatform.cs is compiled into several projects via a Compile Include, so leaving it out
# broke the kit's build with "CS2001: Source file src\Shared/AssemblyPlatform.cs could not be
# found". Anything under src/ with no counterpart in decomp/ is ours by definition, so sweeping
# is both correct and future-proof.
find src -name '*.cs' -not -path '*/obj/*' -not -path '*/bin/*' | sort | while IFS= read -r t; do
  [ -e "$NEWFILES/$t" ] && continue
  base=${t#src/}; rel=${base#*/}
  ours=1
  for a in UnclaimedWorld WindowSystem RoundLines InputEventSystem SpriteSheetRuntime Xclna.Xna.Animationx86; do
    [ -f "decomp/$a/$rel" ] && { ours=0; break; }
  done
  [ "$ours" = 1 ] || continue
  if is_excluded_newfile "$rel"; then continue; fi
  mkdir -p "$NEWFILES/$(dirname "$t")"
  cp -p "$t" "$NEWFILES/$t"
  echo x >> "$TMP/new"
done

echo "    $(wc -l < "$TMP/new" 2>/dev/null || echo 0) new source file(s)"
echo "    $(wc -l < "$TMP/excl" 2>/dev/null || echo 0) excluded as game-derived (regenerated locally)"

echo
echo "==> build system and tools (ours outright)"
for p in Directory.Build.props Directory.Packages.props NuGet.config global.json; do
  cp -p "$p" "$KIT/" && echo "    $p"
done
# src/Directory.Build.props too - it is where TargetFramework lives, keyed off UwPlatform.
# Copying only the ROOT props left the TFM empty and the kit's first build died with
# "NETSDK1013: The TargetFramework value '' was not recognized", which reads like a corrupt
# project rather than a missing file. Collected by search so a future props file is not missed
# the same way.
for p in $(find src -maxdepth 2 -name 'Directory.*.props' -o -maxdepth 2 -name 'Directory.*.targets' | sort); do
  mkdir -p "$KIT/projects/$(dirname "$p")"
  cp -p "$p" "$KIT/projects/$p" && echo "    $p"
done
mkdir -p "$KIT/.config"; cp -p .config/dotnet-tools.json "$KIT/.config/"
# The csproj/props/manifest files: we wrote these (the studio's VS2013 projects never shipped).
for f in $(find src -name '*.csproj' -o -name 'app.manifest' | sort); do
  mkdir -p "$KIT/projects/$(dirname "$f")"; cp -p "$f" "$KIT/projects/$f"
done
echo "    $(find "$KIT/projects" -type f | wc -l) project file(s)"
# app.ico is deliberately absent - see the header.

mkdir -p "$KIT/tools" "$KIT/build"
for t in MgfxTranscode XmlProxyGen ContentProbe DataExport; do
  [ -d "tools/$t" ] || continue
  mkdir -p "$KIT/tools/$t"
  find "tools/$t" -type f \( -name '*.cs' -o -name '*.csproj' \) -not -path '*/obj/*' -not -path '*/bin/*' |
  while IFS= read -r f; do
    skip=0
    for d in $DERIVED_OUTSIDE_SRC; do [ "$f" = "$d" ] && skip=1; done
    [ "$skip" = 0 ] || continue
    mkdir -p "$KIT/$(dirname "$f")"; cp -p "$f" "$KIT/$f"
  done
done
echo "    tools: $(find "$KIT/tools" -name '*.cs' | wc -l) source file(s)"

# ProxyCodeGenerator.cs as a transform of the user's OWN decompiled CustomXmlSerializer.cs.
# build-port.ps1 copies that decompiled file over and applies this, which reconstructs the tool
# without the kit ever carrying the studio's code.
#
# It must diff against the PRE-PATCH decompile: UnclaimedWorld.patch removes 362 lines from
# CustomXmlSerializer.cs - the generator itself - so the patched tree no longer contains it.
CXS=decomp/UnclaimedWorld/UWGame/SimSide/CustomXmlSerializer.cs
PCG=tools/XmlProxyGen/ProxyCodeGenerator.cs
if [ -f "$CXS" ] && [ -f "$PCG" ]; then
  tr -d '\r' < "$CXS" > "$TMP/cxs"; tr -d '\r' < "$PCG" > "$TMP/pcg"
  diff -U1 --label 'a/CustomXmlSerializer.cs' --label 'b/ProxyCodeGenerator.cs' \
    "$TMP/cxs" "$TMP/pcg" > "$PATCHES/ProxyCodeGenerator.patch" || true
  printf '    ProxyCodeGenerator.patch  (+%s ours, %s context lines - was %s bytes verbatim)\n' \
    "$(grep -c '^+[^+]' "$PATCHES/ProxyCodeGenerator.patch")" \
    "$(grep -c '^ ' "$PATCHES/ProxyCodeGenerator.patch")" \
    "$(stat -c%s "$PCG")"
fi

for b in env.sh 20-generate-xml-proxies.sh 33-make-menu-animation.sh 34-make-port-content.sh; do
  [ -f "build/$b" ] && cp -p "build/$b" "$KIT/build/"
done
echo "    build scripts: $(ls -1 "$KIT/build" | wc -l)"

# The version the patches were generated against. build-port.ps1 refuses a mismatch, because a
# patch series against a different decompile fails in confusing ways.
GAMEVER=$(powershell -NoProfile -Command \
  "(Get-Item '$(cygpath -w "$UW_REPO/ref/original/UnclaimedWorld.exe")').VersionInfo.FileVersion" \
  2>/dev/null | tr -d '\r')
{
  echo "# Game version this kit's patch series was generated from."
  echo "# setup-port.ps1 refuses to build against a different version."
  echo "$GAMEVER"
} > "$KIT/game-version.txt"

# SHA-256 of every assembly the kit decompiles, so the build can verify the INPUT rather than
# trusting a version string. A version string is weak evidence: a modded or hand-patched
# assembly reports the same FileVersion and then decompiles differently, which surfaces as a
# patch failing to apply somewhere unrelated. Hashing says exactly which file is wrong.
{
  echo "# SHA-256 of the assemblies this kit's patches were generated against."
  echo "# build-port.ps1 checks these before decompiling anything."
  for a in UnclaimedWorld.exe WindowSystem.dll RoundLines.dll InputEventSystem.dll \
           SpriteSheetRuntime.dll Xclna.Xna.Animationx86.dll; do
    if [ -f "ref/original/$a" ]; then
      printf '%s  %s\n' "$(sha256sum "ref/original/$a" | cut -d' ' -f1)" "$a"
    fi
  done
} > "$KIT/assembly-hashes.txt"
echo "    assembly-hashes.txt ($(grep -c '^[0-9a-f]' "$KIT/assembly-hashes.txt") assemblies)"

# The orchestrator ships as SOURCE and as a BINARY, and only the source is edited here. A fix to
# main.go that never reached uwkit.exe is invisible - the kit looks fixed, and every recipient runs
# the old logic. There is no Go toolchain on this machine, so this cannot rebuild it; it can refuse
# to package a kit whose binary is older than its source, which is the part that matters.
if [ -f kit/orchestrator/main.go ] && [ -f kit/orchestrator/uwkit.exe ]; then
  if [ kit/orchestrator/main.go -nt kit/orchestrator/uwkit.exe ]; then
    echo "FATAL: kit/orchestrator/main.go is newer than uwkit.exe." >&2
    echo "       Rebuild it before packaging, or the kit ships the old orchestrator:" >&2
    echo "         cd kit/orchestrator && GOOS=windows GOARCH=amd64 go build -o uwkit.exe ." >&2
    exit 1
  fi
fi

# A stamp saying WHICH kit this is. Every build report so far has had to be dated by hand, and one
# of them turned out to be a kit whose newfiles/ and patches/ came from different versions - which
# is invisible in a log that only says "8 new source file(s)" unless you know 13 is the right
# number. Both drivers print this line first, so a pasted log identifies itself.
{
  echo "# Which kit this is. Printed by the build so a report identifies itself."
  echo "built:    $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "commit:   $(git -C "$UW_REPO" rev-parse --short HEAD 2>/dev/null || echo unknown)"
  echo "newfiles: $(find "$KIT/newfiles" -name '*.cs' 2>/dev/null | wc -l | tr -d ' ') source file(s)"
  echo "game:     $GAMEVER"
} > "$KIT/kit-version.txt"
echo "    kit-version.txt ($(git -C "$UW_REPO" rev-parse --short HEAD 2>/dev/null || echo unknown))"

echo
echo "==> verifying the kit carries no game code"
BAD=0
for d in decomp src; do
  if [ -e "$KIT/$d" ]; then echo "    ! $KIT/$d exists"; BAD=1; fi
done
if [ -e "$KIT/app.ico" ]; then echo "    ! app.ico present (the studio's icon)"; BAD=1; fi
ASSETS=$(find "$KIT" -name '*.xnb' -o -name '*.uwanim' -o -name '*.wmv' -o -name '*.wma' | head -5)
if [ -n "$ASSETS" ]; then
  echo "$ASSETS" | while IFS= read -r x; do echo "    ! game asset: $x"; done
  BAD=1
fi
# Every .cs in newfiles/ must have NO counterpart in any decompiled tree. This is the check
# that actually matters: it is the difference between shipping files we wrote and shipping the
# studio's, and a mistake here is invisible by inspection because both are just .cs files.
LEAKS=$(find "$KIT" -name "*.cs" 2>/dev/null | while IFS= read -r f; do
  rel=$(echo "$f" | sed "s#^$KIT/newfiles/src/[^/]*/##; s#^$KIT/##")
  for a in UnclaimedWorld WindowSystem RoundLines InputEventSystem SpriteSheetRuntime Xclna.Xna.Animationx86; do
    if [ -f "decomp/$a/$rel" ]; then echo "$rel (also in decomp/$a)"; fi
  done
done)
if [ -n "$LEAKS" ]; then
  echo "$LEAKS" | while IFS= read -r l; do echo "    ! GAME FILE IN newfiles: $l"; done
  BAD=1
fi

if [ "$BAD" = 0 ]; then
  echo "    no decomp/, no src/, no app.ico, no game assets, no game .cs in newfiles/"
else
  echo "FATAL: the kit contains game-derived files - see above" >&2
  exit 1
fi

echo
echo "==> $KIT  ($(du -sh "$KIT" | cut -f1))"
echo "Patch series is generated against game version $GAMEVER."
